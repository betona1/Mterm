def slug(s: str) -> str:
    s = s.lower()
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "x"


def build(terms=TERMS):
    out = []
    seen = set()
    for abbr, term, ko, cat in terms:
        terms_all = [t.strip() for t in term.split("|") if t.strip()]
        abbrs_all = [a.strip() for a in abbr.split("|") if a.strip()]
        tid = slug(terms_all[0])
        if tid in seen:
            raise SystemExit(f"중복 id: {tid} ({term})")
        seen.add(tid)
        out.append({
            "id": tid,
            "term": terms_all[0],
            "termAlts": terms_all[1:],
            "abbr": abbrs_all[0] if abbrs_all else "",
            "abbrAlts": abbrs_all[1:],
            "ko": ko,
            "cat": cat,
        })
    return out


